#!/usr/bin/env node
/**
 * Writes src/lib/utils/pdf-font-widths.ts: the advance widths of the PDF core
 * fonts Times-Roman and Helvetica, by character, as pdf.js ships them.
 *
 * The PDF reader names a link by the text printed under it. pdf.js gives a
 * printed line as one text item with its total width, so the reader splits
 * that width among the characters by their widths in the item's font family.
 * It measured them on a canvas in the generic families "serif" and
 * "sans-serif", which each system resolves to a font of its own: macOS's
 * Times and Helvetica gave the names measured against the PDFs' glyphs, and
 * Linux's fonts lost the number of "Section 4.2". These tables give every
 * system the same widths.
 *
 * pdf.js's worker carries Adobe's metrics for the core fonts (getMetrics, by
 * glyph name, in thousandths of an em) and its glyph list (glyph name to
 * Unicode); this joins the two. The metrics are Adobe's and do not change, so
 * the output changes only if pdf.js changes how it ships them.
 *
 * Usage: node scripts/pdf-font-widths.mjs
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WORKER = join(ROOT, "node_modules/pdfjs-dist/build/pdf.worker.mjs");
const OUT = join(ROOT, "src/lib/utils/pdf-font-widths.ts");
const VERSION = JSON.parse(
  readFileSync(join(ROOT, "node_modules/pdfjs-dist/package.json"), "utf8"),
).version;

const lines = readFileSync(WORKER, "utf8").split("\n");

/** The `t.name = value;` lines of the lookup table opened at `opening`. */
function table(opening, value) {
  const start = lines.findIndex((line) => line.trim() === opening);
  if (start < 0) throw new Error(`Not in pdf.js's worker: ${opening}`);
  const indent = lines[start].match(/^\s*/)[0];
  const entry = new RegExp(
    `^${indent}  t(?:\\.([A-Za-z_$][\\w$]*)|\\["([^"]+)"\\]) = (${value});$`,
  );
  const entries = new Map();
  for (let i = start + 1; lines[i] !== `${indent}});`; i++) {
    const match = lines[i].match(entry);
    if (!match) throw new Error(`Unexpected line ${i + 1}: ${lines[i]}`);
    entries.set(match[1] ?? match[2], Number(match[3]));
  }
  return entries;
}

const unicode = table(
  "const getGlyphsUnicode = getLookupTableFactory(function (t) {",
  "0x[0-9a-fA-F]+",
);

/** A family's widths by character, from its widths by glyph name. */
function byCharacter(font) {
  const widths = table(
    font === "Helvetica"
      ? "t.Helvetica = getLookupTableFactory(function (t) {"
      : `t["${font}"] = getLookupTableFactory(function (t) {`,
    "\\d+",
  );
  const chars = new Map();
  for (const [glyph, width] of widths) {
    const code = unicode.get(glyph);
    if (code === undefined) {
      console.warn(`${font}: no Unicode for ${glyph}, left out`);
      continue;
    }
    const char = String.fromCodePoint(code);
    // Private-use code points stand for glyphs no text content holds.
    if (code >= 0xe000 && code <= 0xf8ff) continue;
    if (!chars.has(char)) chars.set(char, width);
  }
  return [...chars].sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0));
}

const literal = (entries) =>
  `{\n${entries.map(([char, width]) => `  ${JSON.stringify(char)}: ${width},`).join("\n")}\n}`;

const times = byCharacter("Times-Roman");
const helvetica = byCharacter("Helvetica");
const courier = Number(
  lines.find((line) => /^ {2}t\.Courier = \d+;$/.test(line))?.match(/\d+/)?.[0],
);
if (!(courier > 0)) throw new Error("Courier's width is not in the worker");

writeFileSync(
  OUT,
  `/**
 * Advance widths of the PDF core fonts, in thousandths of an em, by
 * character: Adobe's metrics as pdfjs-dist ${VERSION} ships them. The PDF
 * reader weighs the characters of a printed line by them to find the text
 * under a link (pdf-link-names.ts).
 *
 * Generated by scripts/pdf-font-widths.mjs: run it again rather than edit.
 */

export const TIMES_ROMAN: Readonly<Record<string, number>> = ${literal(times)};

export const HELVETICA: Readonly<Record<string, number>> = ${literal(helvetica)};

/** Every character of Courier has the same width. */
export const COURIER = ${courier};
`,
);
execFileSync(join(ROOT, "node_modules/.bin/prettier"), ["--write", OUT], {
  stdio: "ignore",
});
console.log(
  `${OUT}: Times-Roman ${times.length}, Helvetica ${helvetica.length} characters, Courier ${courier}`,
);
